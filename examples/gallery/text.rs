use std::{
    collections::HashMap,
    sync::{
        LazyLock,
        atomic::{AtomicBool, Ordering},
    },
};

static CHINESE: AtomicBool = AtomicBool::new(false);

pub fn set_locale(locale: &wegpui::Locale) {
    CHINESE.store(locale.language() == "zh", Ordering::Relaxed);
}

pub fn tr_or(zh: &'static str, en: &'static str) -> &'static str {
    if is_zh() { zh } else { en }
}

pub fn label_w(zh: f32) -> f32 {
    if is_zh() {
        zh
    } else {
        zh.max(wegpui::components::form::LABEL_MAX_WIDTH)
    }
}

pub fn is_zh() -> bool {
    CHINESE.load(Ordering::Relaxed)
}

static ENGLISH: LazyLock<HashMap<&'static str, &'static str>> =
    LazyLock::new(|| TABLE.iter().copied().collect());

pub fn tr(zh: &'static str) -> &'static str {
    if is_zh() {
        zh
    } else {
        ENGLISH.get(zh).copied().unwrap_or(zh)
    }
}

