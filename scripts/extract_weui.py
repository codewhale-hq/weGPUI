from pathlib import Path
import json, re, sys, urllib.parse
package = Path(sys.argv[1])
root = Path(__file__).resolve().parent.parent
css = (package / 'dist/style/weui.css').read_text()
def root_rules(css):
    pos, start, stack, rules = 0, 0, [], []
    while pos < len(css):
        c = css[pos]
        if c == '{':
            stack.append(css[start:pos].strip())
            start = pos + 1
        elif c == '}':
            body = css[start:pos]
            if stack:
                selector = stack.pop().split('\n')[-1].strip()
                values = re.findall(r'(?m)^\s*--weui-([\w-]+):\s*([^;]+);', body)
                if values and not any(s.startswith('@') for s in stack):
                    rules.append((selector, values))
            start = pos + 1
        pos += 1
    return rules
def matches(selector, dark, care):
    best = None
    for part in selector.split(','):
        part = part.strip()
        if not re.match(r'^(body|\.wx-root|page)(\[|$)', part) or ':not(' in part:
            continue
        attrs = re.findall(r"\[data-weui-(theme|mode)='(\w+)'\]", part)
        ok = all((k == 'theme' and (v == 'dark') == dark) or (k == 'mode' and (v == 'care') == care) for k, v in attrs)
        if ok:
            best = max(best or 0, len(attrs))
    return best
rules = root_rules(css)
palettes = {}
for name, dark, care in [('light', False, False), ('dark', True, False), ('care_light', False, True), ('care_dark', True, True)]:
    chosen = {}
    for order, (selector, values) in enumerate(rules):
        spec = matches(selector, dark, care)
        if spec is None:
            continue
        for k, v in values:
            if k not in chosen or (spec, order) >= chosen[k][0]:
                chosen[k] = ((spec, order), v.strip())
    palettes[name] = {k: v for k, (_, v) in chosen.items()}
light = palettes['light']
(root / 'docs/tokens.json').write_text(json.dumps(palettes, indent=2, ensure_ascii=False)+'\n')
def field(k):
    return re.sub(r'([a-z])([A-Z])',r'\1_\2', k).replace('-', '_').lower()
CALC = {'STEPS-DOT-SIZE': 8.0, 'STEPS-VERTICAL-DOT-GAP': 4.5}
def value(k, v, palette):
    if k in CALC:
        return repr(CALC[k])
    if v.startswith('var('):
        return value(k, palette[v[11:-1]], palette)
    if v.startswith('#'):
        h = v[1:]
        if len(h) == 3: h = ''.join(c*2 for c in h)
        return f'rgb(0x{h}).into()'
    if v.startswith('rgba('):
        parts = [float(x) for x in v[5:-1].split(',')]
        return f'rgba_hsla({parts[0]/255:.9f}, {parts[1]/255:.9f}, {parts[2]/255:.9f}, {parts[3]})'
    return repr(float(v.removesuffix('px')))
def typ(k, v):
    if k in CALC: return 'f32'
    if v.startswith(('#','rgba(','var(')): return 'Hsla'
    return 'f32'
keys = list(light)
for p in palettes.values():
    assert set(p) == set(keys), set(p) ^ set(keys)
lines = ['// Generated by scripts/extract_weui.py from WeUI 2.6.26 dist/style/weui.css. Do not edit.', '',
         'use gpui::{Hsla, rgb};', '', 'fn rgba_hsla(r: f32, g: f32, b: f32, a: f32) -> Hsla {', '    gpui::Rgba { r, g, b, a }.into()', '}', '',
         '#[derive(Clone, Debug, PartialEq)]', 'pub struct Palette {']
lines += [f'    pub {field(k)}: {typ(k, v)},' for k, v in light.items()]
lines += ['}', '', 'impl Palette {']
for name, palette in palettes.items():
    lines += [f'    pub fn {name}() -> Self {{', '        Self {']
    lines += [f'            {field(k)}: {value(k, palette[k], palette)},' for k in keys]
    lines += ['        }', '    }']
lines += ['}']
(root / 'src/theme/palette.rs').parent.mkdir(exist_ok=True)
(root / 'src/theme/palette.rs').write_text('\n'.join(lines)+'\n')
assets = {}
for block in css.split('}'):
    if 'mask-image:' not in block or 'data:image/svg+xml,' not in block: continue
    names = re.findall(r'\.weui-icon-([\w-]+)',block.split('{')[0])
    encoded = None
    for part in block.split('url(')[1:]:
        part=part.lstrip()
        quote=part[0] if part[0] in ('"', "'") else None
        uri=part[1:].split(quote)[0] if quote else part.split(')')[0]
        if uri.startswith('data:image/svg+xml,'):
            encoded=uri.split(',',1)[1]
            break
    if not names or encoded is None: continue
    key = 'icon-'+names[0]+'.svg'
    if key not in assets:
        assets[key]=urllib.parse.unquote(encoded)
for k,v in assets.items(): (root/'assets'/k).write_text(v)
for p in list((package/'src/example/images').glob('*')) + list((package/'src/example/images/layers').glob('*.png')):
    if p.is_file():
        name = ('layers_' if p.parent.name == 'layers' else '') + p.name
        (root/'assets'/name).write_bytes(p.read_bytes())
import base64
EMBEDDED = {'AAAC4AAAAuCAMAAA': 'pic_placeholder_46.png', 'AAAHgAAAB4CAMAAA': 'pic_placeholder_120.png'}
for html in (package/'src/example').rglob('*.html'):
    for data in re.findall(r'data:image/png;base64,([A-Za-z0-9+/=]+)', html.read_text()):
        for key, name in EMBEDDED.items():
            if key in data[:40]:
                (root/'assets'/name).write_bytes(base64.b64decode(data))
from PIL import Image
HUE180 = [(-0.574, 1.43, 0.144), (0.426, 0.43, 0.144), (0.426, 1.43, -0.856)]
def dark_filter(src, dst):
    im = Image.open(src).convert('RGBA')
    px = im.load()
    for y in range(im.height):
        for x in range(im.width):
            r, g, b, a = px[x, y]
            r, g, b = 255 - r, 255 - g, 255 - b
            px[x, y] = tuple(max(0, min(255, round(m[0]*r + m[1]*g + m[2]*b))) for m in HUE180) + (a,)
    im.save(dst)
for name in ['logo.png', 'icon_footer_link.png', 'icon_nav_form.png', 'icon_nav_layout.png', 'icon_nav_feedback.png', 'icon_nav_nav.png', 'icon_nav_search.png', 'icon_nav_z-index.png']:
    dark_filter(root/'assets'/name, root/'assets'/name.replace('.png', '-dark.png'))
